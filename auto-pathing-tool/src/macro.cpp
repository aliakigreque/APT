    // writes the macro as a GDR json file (open replay format, xdBot can read it) at 240 fps
    Result<std::filesystem::path> Macro::exportGDR(std::filesystem::path const& dir, std::string const& levelName,
                                                   int levelId, std::string const& botVersion,
                                                   std::string const& fileSuffix) const {
        std::error_code ec;
        std::filesystem::create_directories(dir, ec);

        auto root = matjson::Value::object();
        root["gameVersion"] = 2.2081;
        root["description"] = "Generated by Auto Pathing Tool (path search)";
        root["version"] = 1.0;
        root["duration"] = toggles.empty() ? 0.0 : static_cast<double>(toggles.back().step) / 240.0;
        auto bot = matjson::Value::object();
        bot["name"] = "Auto Pathing Tool";
        bot["version"] = botVersion;
        root["bot"] = bot;
        auto level = matjson::Value::object();
        level["id"] = levelId;
        level["name"] = levelName;
        root["level"] = level;
        root["author"] = "Auto Pathing Tool";
        root["seed"] = 0;
        root["coins"] = 0;
        root["ldm"] = false;
        root["framerate"] = 240.0;

        auto inputs = matjson::Value::array();
        for (auto const& toggle : toggles) {
            auto input = matjson::Value::object();
            input["frame"] = toggle.step;
            input["btn"] = 1;
            input["2p"] = toggle.p2;
            input["down"] = toggle.down;
            inputs.push(input);
        }
        root["inputs"] = inputs;

        std::string safeName;
        for (char c : levelName) {
            safeName += (std::isalnum(static_cast<unsigned char>(c)) || c == '-' || c == '_') ? c : '_';
        }
        if (safeName.empty()) safeName = "level";
        auto path = dir / fmt::format("{}_{}{}.gdr.json", safeName, levelId, fileSuffix);
        std::error_code existsError;
        for (int n = 2; std::filesystem::exists(path, existsError) && n < 10000; ++n)
            path = dir / fmt::format("{}_{}{}_{}.gdr.json", safeName, levelId, fileSuffix, n);

        auto result = utils::file::writeString(path, root.dump());
        if (!result) return Err(result.unwrapErr());
        return Ok(path);
    }

    // reads a gdr json file, keeps jump inputs and converts frames to 240 ticks per second
    Result<MacroFile> importGDR(std::filesystem::path const& path) {
        auto text = utils::file::readString(path);
        if (!text) return Err(fmt::format("can't read the file ({})", text.unwrapErr()));
        auto parsed = matjson::Value::parse(text.unwrap());
        if (!parsed) return Err("not a GDR macro (invalid JSON)");
        auto const& root = parsed.unwrap();
        if (!root.isObject() || !root.contains("inputs") || !root["inputs"].isArray()) {
            return Err("not a GDR macro (no inputs)");
        }

        MacroFile out;
        if (root.contains("level") && root["level"].isObject()) {
            auto const& level = root["level"];
            if (level.contains("id") && level["id"].isNumber()) {
                out.levelId = static_cast<int>(level["id"].asInt().unwrapOr(std::intmax_t{0}));
            }
            if (level.contains("name") && level["name"].isString()) {
                out.levelName = level["name"].asString().unwrapOr(std::string{});
            }
        }
        double fps = 240.0;
        if (root.contains("framerate") && root["framerate"].isNumber()) {
            fps = root["framerate"].asDouble().unwrapOr(240.0);
        }
        if (!(fps > 0.0)) fps = 240.0;

        for (auto const& input : root["inputs"]) {
            if (!input.isObject() || !input.contains("frame") || !input["frame"].isNumber()) continue;
            int const button = input.contains("btn") && input["btn"].isNumber()
                                       ? static_cast<int>(input["btn"].asInt().unwrapOr(std::intmax_t{1}))
                                       : 1;
            if (button != 1) continue;
            double const frame = input["frame"].asDouble().unwrapOr(0.0);
            Toggle toggle;
            toggle.step = static_cast<int>(std::lround(frame * 240.0 / fps));
            toggle.down = input.contains("down") && input["down"].isBool() && input["down"].asBool().unwrapOr(false);
            toggle.p2 = input.contains("2p") && input["2p"].isBool() && input["2p"].asBool().unwrapOr(false);
            if (toggle.step < 0) continue;
            out.macro.toggles.push_back(toggle);
        }
        std::stable_sort(out.macro.toggles.begin(), out.macro.toggles.end(),
                         [](Toggle const& a, Toggle const& b) { return a.step < b.step; });
        if (out.macro.toggles.empty()) return Err("the macro has no jump inputs");
        return Ok(std::move(out));
    }

